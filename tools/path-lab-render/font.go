// middleDot separates fields in labels; it is the one glyph outside ASCII.
const middleDot = "..... ..... ..... ..#.. ..... ..... ..... ....."

// glyphBits holds each glyph as eight row masks, bit 4 the leftmost column.
var glyphBits = func() (t [128][glyphH]uint8) {
	for c, s := range glyphRows {
		if s != "" {
			t[c] = parseGlyph(s)
		}
	}
	return t
}()

var middleDotBits = parseGlyph(middleDot)

func parseGlyph(s string) (g [glyphH]uint8) {
	for i, row := range strings.Fields(s) {
		for j := 0; j < glyphW && j < len(row); j++ {
			if row[j] == '#' {
				g[i] |= 1 << (glyphW - 1 - j)
			}
		}
	}
	return g
}

// glyph returns the rows of r, or of '?' for a character the font lacks.
func glyph(r rune) [glyphH]uint8 {
	switch {
	case r == '·':
		return middleDotBits
	case r >= 0 && int(r) < len(glyphRows) && glyphRows[r] != "":
		return glyphBits[r]
	}
	return glyphBits['?']
}

// textWidth is the width of s in pixels at scale k.
func textWidth(s string, k int) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return (n*glyphAdv - 1) * k
}

// text draws s with its top-left corner at (x, y), in canvas coordinates.
func (c *canvas) text(x, y int, s string, k int, col rgba) {
	for _, r := range s {
		g := glyph(r)
		for row := 0; row < glyphH; row++ {
			bits := g[row]
			for colIdx := 0; colIdx < glyphW; colIdx++ {
				if bits&(1<<(glyphW-1-colIdx)) != 0 {
					c.fillRectI(x+colIdx*k, y+row*k, k, k, col)
				}
			}
		}
		x += glyphAdv * k
	}
}

// textHalo draws s with a one-pixel dark halo so it reads on the terrain.
func (c *canvas) textHalo(x, y int, s string, k int, col, halo rgba) {
	for dy := -1; dy <= 1; dy++ {
		for dx := -1; dx <= 1; dx++ {
			if dx != 0 || dy != 0 {
				c.text(x+dx, y+dy, s, k, halo)
			}
		}
	}
	c.text(x, y, s, k, col)
}
